/**
 * 游戏逻辑唯一的随机数来源。
 *
 * 逻辑层（systems / core）一律用这里的 random()，不要直接调 Math.random：
 * 暴击、闪避、出兵抖动、龙坑选边这些都会改变对局走向，必须能按种子复现——
 * 测试脚手架和平衡工具靠 seedRandom() 让同一条命令每次跑出同一个结果。
 * 渲染层的纯装饰随机（粒子抖动之类）不影响对局，可以继续用 Math.random。
 *
 * 默认种子是固定的（测试、平衡工具、headless 脚本天然可复现）；真实游戏由
 * main.js 在启动时用时钟重新播种，所以每局不同。
 *
 * 算法：xorshift32。周期 2^32-1，分布对游戏用途足够。
 */
let _s = 0x9e3779b9;

/** 设定种子。同一个种子之后的随机序列逐位相同。 */
export function seedRandom(seed) {
  _s = ((Math.floor(seed) * 2654435761) >>> 0) || 1;
}

/** [0, 1) 均匀分布。 */
export function random() {
  _s ^= _s << 13; _s >>>= 0;
  _s ^= _s >>> 17;
  _s ^= _s << 5; _s >>>= 0;
  return _s / 4294967296;
}
